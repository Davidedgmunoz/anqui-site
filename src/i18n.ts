/** Site-relative URL for a page in a language; Spanish lives at the root, English under /en/. */
export function href(lang: Lang, page: '' | 'privacy' | 'support' | 'credits' = ''): string {
  const base = import.meta.env.BASE_URL.replace(/\/$/, '');
  return `${base}/${lang === 'en' ? 'en/' : ''}${page ? `${page}/` : ''}`;
}
